export interface VideoRef {
  bvid?: string;
  aid?: string;
  /** 分 P，从 1 开始 */
  page?: number;
  /** 起播时间（秒），仅官方 iframe 播放器使用 */
  startSeconds?: number;
}

export const PORT_RANGE = [17321, 17322, 17323, 17324, 17325, 17326, 17327, 17328, 17329, 17330];

export type FitMode = 'cover' | 'contain' | 'fill';

export interface SkinSettings {
  opacity: number;
  blur: number;
  dim: number;
  fit: FitMode;
  muted: boolean;
  autoplay: boolean;
  quality: number;
}

export interface BiliUser {
  mid: number;
  name: string;
  face: string;
  vip: boolean;
}

export interface SkinState {
  visible: boolean;
  openLogin: boolean;
  video: VideoRef | null;
  settings: SkinSettings;
  loggedIn: boolean;
  user: BiliUser | null;
}

export interface StatePatch {
  visible?: boolean;
  openLogin?: boolean;
  video?: VideoRef | null;
  settings?: Partial<SkinSettings>;
}

export interface QualityOption {
  qn: number;
  desc: string;
}

export interface PlayInfo {
  bvid: string;
  cid: number;
  page: number;
  title: string;
  owner: string;
  cover: string;
  duration: number;
  quality: number;
  qualities: QualityOption[];
  url: string;
  backupUrls: string[];
}

export interface LoginQr {
  key: string;
  url: string;
  image: string;
  expiresAt: number;
}

export type LoginPollStatus = 'waiting' | 'scanned' | 'success' | 'expired' | 'error';

export interface LoginPoll {
  status: LoginPollStatus;
  message?: string;
  user?: BiliUser;
}

export interface SkinConfig {
  port: number;
  token: string;
  version: string;
}

export const DEFAULT_SKIN_SETTINGS: SkinSettings = {
  opacity: 0.5,
  blur: 2,
  dim: 0.25,
  fit: 'cover',
  muted: true,
  autoplay: true,
  quality: 80,
};

export function renderSkinConfig(config: SkinConfig): string {
  return `// Generated by vscode-bilibili-player. Do not edit.\nwindow.__BILI_SKIN_CONFIG__ = ${JSON.stringify(config)};\n`;
}
